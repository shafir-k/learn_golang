package main

import "fmt"

func main() {
	// Interfaces in Go
	// - An interface specifies a set of method signatures.
	// - Interfaces are implemented implicitly: no 'implements' keyword needed.
	// - Go philosophy: keep interfaces small (often 1 or 2 methods, e.g. io.Reader, fmt.Stringer).
	fmt.Println("Interfaces in Go")
}
