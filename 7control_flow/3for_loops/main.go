package main

import "fmt"

func main() {
	// The Multi-Functional For Loop in Go
	// - Go has only one looping construct: the 'for' loop.
	// - Standard 3-component: for i := 0; i < n; i++ { ... }.
	// - While-style condition-only: for condition { ... }.
	// - Infinite loop: for { ... }.
	// - Collection iteration: for index, value := range collection { ... }.
	fmt.Println("The Multi-Functional For Loop in Go")
}
