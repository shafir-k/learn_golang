package main

import "fmt"

func main() {
	// Switch Statements in Go
	// - Switch statements do not require explicit 'break'; cases do not fall through by default.
	// - 'fallthrough' explicitly transfers execution to the next case.
	// - Cases can test multiple comma-separated values.
	// - Tagless switches (switch without an expression) act as clean if-else-if ladders.
	fmt.Println("Switch Statements in Go")
}
