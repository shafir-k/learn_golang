package main

import "fmt"

func main() {
	// Conditional Statements (if / else) in Go
	// - Go conditionals do not require parentheses around the condition.
	// - Supports an optional initialization statement: if x := compute(); x > 0 { ... }.
	// - Variables declared in the init statement are scoped only to the if/else blocks.
	fmt.Println("Conditional Statements (if / else) in Go")
}
