package main

import "fmt"

func main() {
	// Control Flow: break, continue, labels, and goto
	// - 'break' terminates the innermost loop or switch.
	// - 'continue' skips to the next iteration of the loop.
	// - Labeled breaks and continues allow jumping to or breaking out of outer nested loops.
	// - 'goto' transfers control to a labeled statement within the same function.
	fmt.Println("Control Flow: break, continue, labels, and goto")
}
