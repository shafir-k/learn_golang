package main

import "fmt"

func main() {
	// Pointers Basics in Go
	// - A pointer holds the memory address of a value: *T points to type T.
	// - The '&' operator generates a pointer to its operand (address-of).
	// - The '*' operator dereferences the pointer to access or modify the underlying value.
	// - Go does not support pointer arithmetic (unlike C/C++), making pointers memory-safe.
	fmt.Println("Pointers Basics in Go")
}
