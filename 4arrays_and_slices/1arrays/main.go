package main

import "fmt"

func main() {
	// Arrays in Go
	// - Arrays have a fixed size defined at declaration: [N]T.
	// - The array size is part of its type: [3]int and [4]int are distinct, incompatible types.
	// - Arrays are value types: assigning or passing an array copies the entire array in memory.
	fmt.Println("Arrays in Go")
}
